import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';

const base = process.env.TEST_URL || 'http://127.0.0.1:8082';
const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const login = await context.request.post(`${base}/api/auth/login`,{data:{username:process.env.ADMIN_USER,password:process.env.ADMIN_PASSWORD}});
assert.equal(login.status(),200,'Login');
const {token} = await login.json();
const headers = {Authorization:`Bearer ${token}`};
const request = (method,url,data) => context.request.fetch(`${base}${url}`,{method,headers,data});
const ids = [];
const prefix = `E2E-INV-${Date.now()}`;
try {
  assert.equal((await context.request.get(`${base}/api/devices`)).status(),401);
  assert.equal((await context.request.post(`${base}/api/devices`,{data:{}})).status(),401);
  await page.goto(base,{waitUntil:'networkidle'});
  await page.evaluate(t=>sessionStorage.setItem('mesaTiToken',t),token);
  await page.getByRole('button',{name:/Acceso de TI/}).click();
  await page.locator('#adminShell').waitFor({state:'visible'});
  await page.locator('#inventoryNav').click();
  await page.locator('#invLoadStatus').waitFor({state:'hidden'});
  await page.locator('#invAdd').click();
  const form = page.locator('#invForm');
  await form.locator('[name=name]').fill(`${prefix}-PC`);
  await form.locator('[name=kind]').selectOption('laptop');
  assert.equal(await form.locator('[name=kind]').inputValue(),'laptop');
  await form.locator('[name=kind]').selectOption('desktop');
  await form.locator('[name=area]').fill('Sistemas E2E');
  await form.locator('[name=owner]').fill('Responsable de prueba');
  await form.locator('[name=password]').fill('E2E-password-only');
  await form.locator('[name=last_maintenance]').fill('2026-09-01');
  await page.locator('#invChoosePosition').click();
  await page.locator('#invZoomIn').click();
  const rect = await page.locator('#invPlan').boundingBox();
  await page.locator('#invPlan').click({position:{x:rect.width*.3,y:rect.height*.25}});
  await page.locator('#deviceDialog').waitFor({state:'visible'});
  assert.ok(Math.abs(Number(await form.locator('[name=x]').inputValue())-30)<.2);
  assert.ok(Math.abs(Number(await form.locator('[name=y]').inputValue())-25)<.2);
  await page.locator('#invSave').click();
  await page.locator('#deviceDialog').waitFor({state:'hidden'});
  let devices = await (await request('GET','/api/devices')).json();
  const desktop = devices.find(d=>d.name===`${prefix}-PC`);
  assert.ok(desktop); ids.push(desktop.id);
  assert.equal(desktop.has_password,true);
  assert.ok(!JSON.stringify(devices).includes('E2E-password-only'));
  assert.equal(desktop.last_maintenance,'2026-09-01');
  assert.equal((await context.request.get(`${base}/api/devices/${desktop.id}/password`)).status(),401);
  await page.locator(`.inv-marker[data-device="${desktop.id}"]`).click();
  await page.locator('#invReveal').click();
  await page.waitForFunction(()=>document.querySelector('#invForm [name=password]').type==='text');
  assert.equal(await form.locator('[name=password]').inputValue(),'E2E-password-only');
  await form.locator('[name=owner]').fill('Responsable actualizado');
  await page.locator('#invSave').click();
  await page.locator('#deviceDialog').waitFor({state:'hidden'});
  assert.equal((await (await request('GET',`/api/devices/${desktop.id}/password`)).json()).password,'E2E-password-only');
  const payload={name:`${prefix}-Laptop`,kind:'laptop',area:'Calidad E2E',owner:'Prueba portátil',x:null,y:null};
  const created=await request('POST','/api/devices',payload);
  assert.equal(created.status(),201);const laptop=await created.json();ids.push(laptop.id);
  assert.equal((await request('POST','/api/devices',payload)).status(),409);
  assert.equal((await request('POST','/api/devices',{...payload,name:prefix+'-Invalid',x:101,y:0})).status(),400);
  assert.equal((await request('POST','/api/devices',{...payload,name:prefix+'-Invalid',kind:'printer'})).status(),400);
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:/Acceso de TI/}).click();
  await page.locator('#inventoryNav').click();await page.locator('#invLoadStatus').waitFor({state:'hidden'});
  await page.locator('#invSearch').fill(prefix);
  assert.equal(await page.locator('.inv-table tbody tr').count(),2);
  await page.locator('#invKind').selectOption('laptop');
  assert.equal(await page.locator('.inv-table tbody tr').count(),1);
  await page.locator('#invKind').selectOption('');
  await page.screenshot({path:path.join(os.tmpdir(),'mesa-inventory-list.png'),fullPage:true});
  await page.locator('[data-inv-view=map]').click();
  await page.locator(`#invUnplaced [data-place="${laptop.id}"]`).click();
  const mapRect=await page.locator('#invPlan').boundingBox();
  await page.locator('#invPlan').click({position:{x:mapRect.width*.4,y:mapRect.height*.35}});
  await page.locator('#invSave').click();await page.locator('#deviceDialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('.inv-marker.laptop').count(),1);
  await page.screenshot({path:path.join(os.tmpdir(),'mesa-inventory-map.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-inv-view=list]').click();
  await page.locator(`.inv-device-link[data-device="${desktop.id}"]`).click();
  await form.locator('[name=notes]').fill('Edición desde móvil');
  await page.locator('#invSave').click();await page.locator('#deviceDialog').waitFor({state:'hidden'});
  assert.equal((await (await request('GET','/api/devices')).json()).find(d=>d.id===desktop.id).notes,'Edición desde móvil');
  await page.screenshot({path:path.join(os.tmpdir(),'mesa-inventory-mobile.png'),fullPage:true});
  if(!await page.locator('[data-view=dashboard]').isVisible()) await page.locator('#menuButton').click();
  await page.locator('[data-view=dashboard]').click();
  assert.equal(await page.locator('#dashboard').isVisible(),true);
  assert.equal(await page.locator('#inventoryPage').isVisible(),false);
  assert.deepEqual(errors,[]);
  console.log('Inventario: alta, edición, cifrado, permisos, filtros, ubicación con zoom, persistencia, laptop, móvil y navegación: OK');
} catch (error) {
  await page.screenshot({path:path.join(os.tmpdir(),'mesa-inventory-failure.png'),fullPage:true});
  console.log(await page.locator('#invPlan').boundingBox());
  console.log('Errores de JavaScript:',errors);
  throw error;
} finally {
  for(const id of ids) await request('DELETE',`/api/devices/${id}`);
  await browser.close();
}
